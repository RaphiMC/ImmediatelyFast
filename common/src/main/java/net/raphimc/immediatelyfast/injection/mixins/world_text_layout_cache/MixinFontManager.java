package net.raphimc.immediatelyfast.injection.mixins.world_text_layout_cache;

import net.minecraft.client.gui.font.FontManager;
import net.raphimc.immediatelyfast.feature.world_text_layout_cache.WorldTextLayoutCache;
import org.spongepowered.asm.mixin.Mixin;
import org.spongepowered.asm.mixin.injection.At;
import org.spongepowered.asm.mixin.injection.Inject;
import org.spongepowered.asm.mixin.injection.callback.CallbackInfo;

@Mixin(FontManager.class)
public abstract class MixinFontManager {

    @Inject(method = {"apply", "updateOptions"}, at = @At("RETURN"), require = 2)
    private void clearWorldTextLayoutCache(final CallbackInfo ci) {
        WorldTextLayoutCache.clear();
    }

}
