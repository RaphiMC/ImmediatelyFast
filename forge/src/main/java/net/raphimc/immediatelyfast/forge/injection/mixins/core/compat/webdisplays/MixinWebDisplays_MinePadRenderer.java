package net.raphimc.immediatelyfast.forge.injection.mixins.core.compat.webdisplays;

import net.minecraft.client.render.RenderLayer;
import net.minecraft.client.render.VertexConsumer;
import net.minecraft.client.render.VertexConsumerProvider;
import org.spongepowered.asm.mixin.Mixin;
import org.spongepowered.asm.mixin.Pseudo;
import org.spongepowered.asm.mixin.injection.At;
import org.spongepowered.asm.mixin.injection.Redirect;

@SuppressWarnings("UnresolvedMixinReference")
@Mixin(targets = "net.montoyo.wd.client.renderers.MinePadRenderer", remap = false)
@Pseudo
public abstract class MixinWebDisplays_MinePadRenderer {

    @Redirect(method = "render", at = @At(value = "INVOKE", target = "Lnet/minecraft/client/render/VertexConsumerProvider;getBuffer(Lnet/minecraft/client/render/RenderLayer;)Lnet/minecraft/client/render/VertexConsumer;"))
    private VertexConsumer fixForceDraw(VertexConsumerProvider vertexConsumerProvider, RenderLayer renderLayer) {
        if (vertexConsumerProvider instanceof VertexConsumerProvider.Immediate immediate) {
            immediate.drawCurrentLayer();
            return null;
        } else {
            return vertexConsumerProvider.getBuffer(renderLayer);
        }
    }

}
